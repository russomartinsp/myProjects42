#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	size_t				i;
	unsigned char		*j;

	i = 0;
	j = (unsigned char *)s;
	while (i < n)
	{
		j[i] = '\0';
		i++;
	}
}
